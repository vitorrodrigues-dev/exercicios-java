package review_fase5.ex2;

public class Main {
    public static void main(String[] args) {


        for (int i = 5; i <= 15; i++) {
            System.out.println("Números: " + i);
        }

        int jj = 16;
        while (jj <= 30) {
            System.out.println("Números: " + jj);
            jj++;
        }

        int hh = 31;
        do {
            System.out.println("Números: " + hh);
            hh++;
        } while (hh <= 45);
    }
}


